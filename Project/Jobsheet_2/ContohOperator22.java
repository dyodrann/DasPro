        System.out.println("Hasil dari a * c = " + (a*c));
        System.out.println("Hasil dari a / b = " + (a/b)); 
        System.out.println("Hasil dari a % b = " + (a%b));
        System.out.println("Hasil dari a + b * c= " + (a+b*c));
        System.out.println("Hasil dari (a + b) *c = " + ((a+b)*c));
